"""
Security rule engine for evaluating events and generating alerts.

Rules are designed to be:
- Stateless (for easy horizontal scaling)
- Configurable via environment variables
- Testable in isolation
- Extensible without modifying core logic
"""

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Optional, Protocol, List, Dict
import logging
import re
import os

logger = logging.getLogger(__name__)


# =============================================================================
# Domain Types
# =============================================================================

class Severity(Enum):
    """Alert severity levels with numeric priority for sorting."""
    LOW = 1
    MEDIUM = 2
    HIGH = 3
    CRITICAL = 4
    
    def __lt__(self, other):
        return self.value < other.value


@dataclass
class Alert:
    """
    Represents a security alert generated by a rule.
    
    Immutable dataclass ensures thread-safety when rules run concurrently.
    """
    severity: Severity
    message: str
    rule_id: str
    event_id: Optional[int] = None
    metadata: Dict[str, str] = field(default_factory=dict)
    created_at: datetime = field(default_factory=datetime.utcnow)
    
    def to_dict(self) -> dict:
        """Serialize for API responses."""
        return {
            "severity": self.severity.name.lower(),
            "message": self.message,
            "rule_id": self.rule_id,
            "event_id": self.event_id,
            "metadata": self.metadata,
            "created_at": self.created_at.isoformat(),
        }


class RuleProtocol(Protocol):
    """
    Protocol defining the interface for security rules.
    
    Using Protocol enables duck-typing while maintaining type safety.
    """
    
    def evaluate(self, event: dict) -> Optional[Alert]:
        """
        Evaluate an event and return an Alert if the rule triggers.
        
        Args:
            event: Dictionary containing event data from eBPF agent
            
        Returns:
            Alert if rule matches, None otherwise
        """
        ...


# =============================================================================
# Base Rule Implementation
# =============================================================================

class BaseRule:
    """
    Base class providing common functionality for rules.
    
    Includes logging, metadata enrichment, and helper methods.
    """
    
    rule_id: str = "base_rule"
    description: str = "Base rule class - should not be used directly"
    
    def __init__(self, enabled: bool = True):
        self.enabled = enabled
        self.logger = logging.getLogger(f"{__name__}.{self.rule_id}")
    
    def evaluate(self, event: dict) -> Optional[Alert]:
        """Template method - delegates to _check() if enabled."""
        if not self.enabled:
            return None
        
        try:
            return self._check(event)
        except Exception as e:
            self.logger.error(f"Rule evaluation failed: {e}", exc_info=True)
            return None
    
    def _check(self, event: dict) -> Optional[Alert]:
        """Override this method in subclasses."""
        raise NotImplementedError
    
    def _create_alert(
        self,
        severity: Severity,
        message: str,
        event: dict,
        **metadata
    ) -> Alert:
        """Helper to create alerts with consistent metadata."""
        return Alert(
            severity=severity,
            message=message,
            rule_id=self.rule_id,
            event_id=event.get("id"),
            metadata={
                "pid": str(event.get("pid")),
                "uid": str(event.get("uid")),
                **metadata
            }
        )


