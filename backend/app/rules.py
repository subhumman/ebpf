# Rule Engine
# =============================================================================

class RuleEngine:
    """
    Orchestrates rule evaluation for incoming events.
    
    Thread-safe and designed for concurrent evaluation.
    """
    
    def __init__(self, rules: Optional[List[RuleProtocol]] = None):
        """
        Initialize with default rules or custom list.
        
        Args:
            rules: Optional list of RuleProtocol instances.
                  If None, loads default rules from environment.
        """
        self.rules = rules or self._load_default_rules()
        self.logger = logging.getLogger(__name__)
        self.logger.info(f"Initialized RuleEngine with {len(self.rules)} rules")
    
    def _load_default_rules(self) -> List[RuleProtocol]:
        """Load default rules with environment-based configuration."""
        return [
            SensitiveFileAccessRule(),
            SuspiciousPortRule(),
            RootActivityRule(),
            ExecutableWriteRule(),
        ]
    
    def evaluate(self, event: dict) -> List[Alert]:
        """
        Evaluate an event against all enabled rules.
        
        Args:
            event: Event dictionary from eBPF agent
            
        Returns:
            List of triggered alerts (may be empty)
        """
        alerts = []
        
        for rule in self.rules:
            try:
                alert = rule.evaluate(event)
                if alert:
                    alerts.append(alert)
            except Exception as e:
                self.logger.error(
                    f"Unhandled error in rule {rule.rule_id}: {e}",
                    exc_info=True
                )
                # Continue evaluating other rules - don't let one failure block all
        
        return alerts
    
    def get_rule_info(self) -> List[dict]:
        """Return metadata about loaded rules for API documentation."""
        return [
            {
                "rule_id": rule.rule_id,
                "description": getattr(rule, "description", "No description"),
                "enabled": getattr(rule, "enabled", True),
            }
            for rule in self.rules
        ]
    
    def enable_rule(self, rule_id: str) -> bool:
        """Enable a rule by ID. Returns True if found."""
        for rule in self.rules:
            if rule.rule_id == rule_id:
                rule.enabled = True
                self.logger.info(f"Enabled rule: {rule_id}")
                return True
        return False
    
    def disable_rule(self, rule_id: str) -> bool:
        """Disable a rule by ID. Returns True if found."""
        for rule in self.rules:
            if rule.rule_id == rule_id:
                rule.enabled = False
                self.logger.info(f"Disabled rule: {rule_id}")
                return True
        return False


# Global instance for dependency injection
rule_engine = RuleEngine()