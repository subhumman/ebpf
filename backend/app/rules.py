# Concrete Rules
# =============================================================================

class SensitiveFileAccessRule(BaseRule):
    """
    Detects access to sensitive system files.
    
    Configurable via SENSITIVE_FILE_PATTERNS env var (comma-separated regex).
    """
    
    rule_id = "sensitive_file_access"
    description = "Alert on access to sensitive files like /etc/shadow"
    
    DEFAULT_PATTERNS = [
        r"^/etc/(shadow|passwd|sudoers|ssh/)",
        r"^/root/\.ssh/",
        r"\.ssh/id_(rsa|ed25519)$",
        r"\.kube/config$",
        r"\.aws/credentials$",
    ]
    
    def __init__(self, enabled: bool = True, patterns: Optional[List[str]] = None):
        super().__init__(enabled)
        
        # Load patterns from env or use defaults
        env_patterns = os.getenv("SENSITIVE_FILE_PATTERNS")
        if env_patterns:
            self.patterns = [p.strip() for p in env_patterns.split(",") if p.strip()]
        else:
            self.patterns = patterns or self.DEFAULT_PATTERNS
        
        # Pre-compile regex for performance
        self.compiled_patterns = [re.compile(p, re.IGNORECASE) for p in self.patterns]
    
    def _check(self, event: dict) -> Optional[Alert]:
        # Only evaluate file events
        if event.get("event_type") != 1:  # EVENT_FILE_OPEN
            return None
        
        filename = event.get("filename", "")
        if not filename:
            return None
        
        for pattern in self.compiled_patterns:
            if pattern.search(filename):
                uid = event.get("uid", -1)
                
                # Higher severity for root accessing sensitive files
                if uid == 0:
                    severity = Severity.CRITICAL
                    message = f"Root accessed sensitive file: {filename}"
                else:
                    severity = Severity.HIGH
                    message = f"Non-root user accessed sensitive file: {filename}"
                
                self.logger.info(f"Rule triggered: {message}")
                return self._create_alert(severity, message, event, filename=filename)
        
        return None


class SuspiciousPortRule(BaseRule):
    """
    Detects connections to known malicious or suspicious ports.
    
    Port lists can be extended via SUSPICIOUS_PORTS env var.
    """
    
    rule_id = "suspicious_port"
    description = "Alert on connections to suspicious ports"
    
    # Common backdoor/C2 ports
    DEFAULT_PORTS = {
        4444,   # Metasploit default
        5555,   # Android debug / backdoor
        6666,   # IRC backdoor
        31337,  # "Elite" hacker port
        12345,  # NetBus
        1234,   # Common test backdoor
        65535,  # Often used in exploits
    }
    
    def __init__(self, enabled: bool = True, ports: Optional[set] = None):
        super().__init__(enabled)
        
        # Load from env: SUSPICIOUS_PORTS=4444,5555,9999
        env_ports = os.getenv("SUSPICIOUS_PORTS")
        if env_ports:
            try:
                self.ports = {int(p.strip()) for p in env_ports.split(",") if p.strip()}
            except ValueError:
                logger.warning(f"Invalid SUSPICIOUS_PORTS format: {env_ports}")
                self.ports = self.DEFAULT_PORTS
        else:
            self.ports = ports or self.DEFAULT_PORTS
    
    def _check(self, event: dict) -> Optional[Alert]:
        # Only evaluate network events
        if event.get("event_type") != 2:  # EVENT_NETWORK_CONNECT
            return None
        
        port = event.get("dest_port")
        if port is None or port not in self.ports:
            return None
        
        dest_ip = event.get("dest_ip", "unknown")
        pid = event.get("pid", "unknown")
        
        message = f"Process {pid} connected to suspicious port {port} on {dest_ip}"
        
        self.logger.warning(f"Rule triggered: {message}")
        return self._create_alert(
            Severity.CRITICAL,
            message,
            event,
            dest_ip=dest_ip,
            dest_port=str(port)
        )


class RootActivityRule(BaseRule):
    """
    Monitors activity from root user (UID 0).
    
    Not all root activity is malicious, so this generates MEDIUM severity
    alerts for audit purposes rather than immediate blocking.
    """
    
    rule_id = "root_activity"
    description = "Log significant activity from root user"
    
    # Only alert on these event types to reduce noise
    MONITORED_TYPES = {1, 2}  # FileOpen, NetworkConnect
    
    def __init__(self, enabled: bool = True, exclude_paths: Optional[List[str]] = None):
        super().__init__(enabled)
        self.exclude_paths = exclude_paths or ["/proc/", "/sys/"]
    
    def _check(self, event: dict) -> Optional[Alert]:
        # Only evaluate if UID is root
        if event.get("uid") != 0:
            return None
        
        # Filter by event type
        if event.get("event_type") not in self.MONITORED_TYPES:
            return None
        
        # Exclude noisy paths
        filename = event.get("filename", "")
        if any(filename.startswith(excl) for excl in self.exclude_paths):
            return None
        
        event_type = event.get("event_type")
        target = filename or f"{event.get('dest_ip')}:{event.get('dest_port')}"
        
        message = f"Root activity: {'file access' if event_type == 1 else 'network connection'} to {target}"
        
        # Debug-level logging to avoid spam
        self.logger.debug(f"Rule triggered: {message}")
        return self._create_alert(
            Severity.MEDIUM,
            message,
            event,
            target=target
        )


class ExecutableWriteRule(BaseRule):
    """
    Detects writes to executable paths (potential malware drop).
    
    Uses simple path heuristics - can be extended with file hash checking.
    """
    
    rule_id = "executable_write"
    description = "Alert on writes to executable directories"
    
    EXECUTABLE_DIRS = [
        "/usr/bin", "/usr/sbin", "/usr/local/bin",
        "/bin", "/sbin",
        "/opt/",
    ]
    
    EXECUTABLE_EXTENSIONS = {".sh", ".py", ".pl", ".rb", ".so", ".ko"}
    
    def _check(self, event: dict) -> Optional[Alert]:
        if event.get("event_type") != 1:
            return None
        
        filename = event.get("filename", "")
        if not filename:
            return None
        
        # Check if writing to executable directory
        is_exec_dir = any(filename.startswith(d) for d in self.EXECUTABLE_DIRS)
        
        # Check if file has executable extension
        has_exec_ext = any(filename.endswith(ext) for ext in self.EXECUTABLE_EXTENSIONS)
        
        if is_exec_dir or has_exec_ext:
            message = f"Write to executable path: {filename}"
            severity = Severity.HIGH if is_exec_dir else Severity.MEDIUM
            
            self.logger.info(f"Rule triggered: {message}")
            return self._create_alert(severity, message, event, filename=filename)
        
        return None


